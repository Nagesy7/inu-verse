#!/usr/bin/env bash
# Rebuilds the two vendored bundles used by the no-extension launch (Inu Verse has no build step):
#   src/vendor/phantom-kit.js  browser ESM: @phantom/browser-sdk + @solana/web3.js (Keypair, VersionedTransaction, PublicKey) + qrcode-generator
#   api/_lib/pumpkit.cjs       server CJS: pump.fun's official @pump-fun/pump-sdk (instruction builders) + web3.js
set -euo pipefail; ROOT=$(cd "$(dirname "$0")/.." && pwd); T=$(mktemp -d); cd "$T"; npm init -y >/dev/null
npm i @phantom/browser-sdk@2.0.4 @solana/web3.js@1.98.4 @pump-fun/pump-sdk@4.1.0 bn.js qrcode-generator@1.4.4 buffer esbuild >/dev/null
cat > b.js <<'J'
import { Buffer } from 'buffer'; if (!globalThis.Buffer) globalThis.Buffer = Buffer;
export { BrowserSDK, AddressType, base64urlDecode, base64urlEncode } from '@phantom/browser-sdk';
export { Keypair, VersionedTransaction, PublicKey } from '@solana/web3.js';
import qrcode from 'qrcode-generator'; export { qrcode };
J
cat > s.cjs <<'J'
const P = require('@pump-fun/pump-sdk'), W = require('@solana/web3.js'), BN = require('bn.js');
module.exports = { PUMP_SDK: P.PUMP_SDK, OnlinePumpSdk: P.OnlinePumpSdk, getBuyTokenAmountFromSolAmount: P.getBuyTokenAmountFromSolAmount, GLOBAL_PDA: P.GLOBAL_PDA, PUMP_FEE_CONFIG_PDA: P.PUMP_FEE_CONFIG_PDA, PUMP_PROGRAM_ID: P.PUMP_PROGRAM_ID, BN,
  Connection: W.Connection, PublicKey: W.PublicKey, TransactionMessage: W.TransactionMessage, VersionedTransaction: W.VersionedTransaction, ComputeBudgetProgram: W.ComputeBudgetProgram, LAMPORTS_PER_SOL: W.LAMPORTS_PER_SOL };
J
npx esbuild b.js --bundle --format=esm --platform=browser --minify --target=es2020 --define:process.env.NODE_ENV='"production"' --define:global=globalThis --legal-comments=none \
  --banner:js="/* phantom-kit: @phantom/browser-sdk@2.0.4 + @solana/web3.js@1.98.4 (Keypair, VersionedTransaction, PublicKey) + qrcode-generator@1.4.4. Generated by scripts/build-vendor.sh; do not edit. */" --outfile="$ROOT/src/vendor/phantom-kit.js"
npx esbuild s.cjs --bundle --platform=node --format=cjs --target=node18 --minify --outfile="$ROOT/api/_lib/pumpkit.cjs"
echo "rebuilt vendored bundles"
