#!/usr/bin/env python3
"""Pack /workspace/inu-art/verse-outfits (manifest.json) into one trimmed, palette-quantized
atlas per coat: assets/outfits/<coat>.png + src/outfit-atlas.js (frame rects + offsets)."""
import json, sys, os
from PIL import Image
SRC = sys.argv[1] if len(sys.argv) > 1 else '/workspace/inu-art/verse-outfits'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M = json.load(open(os.path.join(SRC, 'manifest.json')))
VIEWS = ['front', 'side', 'back']
out = {'canvas': M['canvas'], 'frames_per_sheet': M['frames_per_sheet'], 'items': {}, 'frames': {}}
for iid, it in M['items'].items():
    out['items'][iid] = {'slot': it['slot'], 'z': it['z'], 'replacesBottom': bool(it.get('replaces_bottom')),
                         'coats': sorted(c for c, v in it['files'].items() if all(k in v for k in VIEWS))}  # manifest has a layer file for all 3 views
for coat, (cw, ch) in M['canvas'].items():
    sprites = []  # (key, img, ox, oy)
    def add(iid, view, spec):
        sheet = Image.open(os.path.join(SRC, spec['file'])).convert('RGBA')
        for f, (x, y, w, h) in enumerate(spec['frames']):
            fr = sheet.crop((x, y, x + w, y + h)); bb = fr.getbbox()
            if not bb: continue
            sprites.append((f'{iid}|{view}|{f}', fr.crop(bb), bb[0], bb[1]))
    for v in VIEWS: add('base', v, {'file': M['bases'][coat][v], 'frames': [[i * cw, 0, cw, ch] for i in range(4)]})
    for iid, it in M['items'].items():
        for v in VIEWS: add(iid, v, it['files'][coat][v])
    # shelf pack, tallest first
    sprites.sort(key=lambda s: -s[1].height); W = 1024; x = y = sh = 0; rects = {}
    for k, im, ox, oy in sprites:
        if x + im.width > W: x, y, sh = 0, y + sh + 1, 0
        rects[k] = [x, y, im.width, im.height, ox, oy]; x += im.width + 1; sh = max(sh, im.height)
    atlas = Image.new('RGBA', (W, y + sh), (0, 0, 0, 0))
    for k, im, ox, oy in sprites: atlas.paste(im, tuple(rects[k][:2]))
    q = atlas.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    q.save(os.path.join(ROOT, 'assets/outfits', f'{coat}.png'), optimize=True)
    out['frames'][coat] = rects
with open(os.path.join(ROOT, 'src/outfit-atlas.js'), 'w') as f:
    f.write('// GENERATED by scripts/build_outfit_atlas.py from inu-art/verse-outfits/manifest.json - do not edit.\n')
    f.write('// frames[coat]["<item|base>|<front|side|back>|<0-3>"] = [sx, sy, w, h, offsetX, offsetY] inside the coat canvas.\n')
    f.write('export const OUTFIT_ATLAS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print('ok')
