test('Sprig and the player are paid from the same finite pool and the gate wears only once more', () => {
  let s = seedGrove();
  assert.equal(GATE_RENEW_MAX, 1);
  assert.equal(GATE_USES, 3);
  const open = moneySum(s);
  assert.equal(open, OPEN_BUDGET);
  actAt(s, 'stump');
  s = walk(s, STATIONS.stump, STATIONS.saw);
  actAt(s, 'saw');
  s = walk(s, STATIONS.saw, STATIONS.shed);
  actAt(s, 'shed');
  s = walk(s, STATIONS.shed, STATIONS.porch);
  actAt(s, 'porch');
  assert.equal(s.you, WAGE);
  assert.equal(s.holes, 0);
  let guard = 12000;
  const clock = { t: 100000 };
  while (s.sprigWallet < WAGE && guard--) fore(s, 1, clock);
  assert.ok(guard > 0, 'Sprig did not finish the gate');
  assert.equal(s.sprigWallet, WAGE);
  assert.equal(s.you, WAGE);
  assert.equal(s.gateHoles, 0);
  assert.equal(s.npcHold, 0);
  assert.equal(moneySum(s), open);
  const blocked = actAt(seedGrove(), 'gate');
  assert.equal(blocked.ok, false);
  guard = 20000;
  while ((s.sprigWallet < WAGE * 2 || s.gateHoles > 0) && guard--) fore(s, 1, clock);
  assert.ok(guard > 0, 'the one renewal did not finish');
  assert.equal(s.gateRenewed, 1);
  assert.equal(s.gateHoles, 0);
  assert.equal(s.sprigWallet, WAGE * 2);
  assert.equal(s.you, WAGE);
  assert.equal(moneySum(s), open);
  assert.equal(s.budget, OPEN_BUDGET - WAGE * 3);
  const wallet = s.sprigWallet;
  const holes = s.gateHoles;
  fore(s, 4000, clock);
  assert.equal(s.gateHoles, holes);
  assert.equal(s.sprigWallet, wallet);
  assert.equal(moneySum(s), open);
  assert.match(actAt(s, 'shed').msg, /will not wear again|not reserved|No splints are paid/);
});

