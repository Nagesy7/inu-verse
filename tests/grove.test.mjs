function fore(s, frames, now = { t: 5000 }) {
  for (let i = 0; i < frames; i++) {
    now.t += 40;
    noteMotion(s, { x: s.play?.x || 0, y: s.play?.y || 0, now: now.t, input: false, foreground: true });
  }
  return s;
}

