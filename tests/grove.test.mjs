class Mem {
  constructor() { this.m = new Map(); }
  getItem(k) { return this.m.has(k) ? this.m.get(k) : null; }
  setItem(k, v) { this.m.set(k, String(v)); }
}

function walk(s, from, to, now = { t: 1000 }) {
  noteMotion(s, { x: from.x, y: from.y, now: now.t, input: true, foreground: true });
  const dist = Math.hypot(to.x - from.x, to.y - from.y);
  const steps = Math.max(1, Math.ceil(dist / 5));
  for (let i = 1; i <= steps; i++) {
    now.t += 40;
    noteMotion(s, {
      x: from.x + (to.x - from.x) * (i / steps),
      y: from.y + (to.y - from.y) * (i / steps),
      now: now.t, input: true, foreground: true,
    });
  }
  let guard = 50;
  while (s.job && s.job.activeMs < MIN_ACTIVE_MS && guard--) {
    now.t += 40;
    const j = guard % 2 ? 4 : -4;
    noteMotion(s, { x: to.x + j, y: to.y, now: now.t, input: true, foreground: true });
  }
  return s;
}

